rows = []

def P(npc, slot, text, intent=None, topic=None, **kw):
    p = {'slot': slot, 'text': text}
    if npc: p['npc'] = npc
    if intent: p['intent'] = intent.split() if isinstance(intent, str) else intent
    if topic: p['topic'] = topic.split() if isinstance(topic, str) else topic
    for k, v in kw.items():
        if k == 'after' or k == 'answer' or k == 'needs' or k == 'emotion' or k == 'when' or k == 'channel' or k == 'where':
            v = v.split() if isinstance(v, str) else v
        p[k] = v
    for var in ('dish', 'event', 'weather', 'item', 'place', 'holiday', 'amount'):
        if '{' + var + '}' in text and var not in p.get('needs', []):
            p.setdefault('needs', []).append(var)
    rows.append(p)

