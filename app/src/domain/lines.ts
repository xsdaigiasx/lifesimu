export function chooseLine(intent:string,voice:Voice,score:number,heard:string[],seed:number):Line|undefined{const fit=LINES.filter(l=>l.intent===intent&&(l.min??0)<=score&&score<=(l.max??100));if(!fit.length)return undefined;const voiced=fit.filter(l=>l.voice===voice),generic=fit.filter(l=>!l.voice),pool=[...voiced,...voiced,...generic];const fresh=pool.filter(l=>!heard.includes(l.id));const from=fresh.length?fresh:pool.filter(l=>l.id!==heard[heard.length-1]);return (from.length?from:pool)[seed%(from.length?from.length:pool.length)]}
